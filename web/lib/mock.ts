/** 按 feature 返回 mock 回复（支持关键字分流的简单逻辑） */
export function getMockReply(feature: FeatureId, userText: string): MockReply {
  switch (feature) {
    case "hotspot-radar":
      return { reply: HOTSPOT_REPLY, delayMs: 2200 };
    case "rural-scriptwriter":
      return { reply: SCRIPTWRITER_REPLY, delayMs: 2600 };
    case "live-coach":
      return { reply: LIVECOACH_REPLY, delayMs: 2400 };
    case "promo-materials": {
      const t = userText.trim();
      if (t === "2" || t.includes("海报") || t.includes("做图")) {
        return {
          reply: MATERIAL_POSTER_REPLY,
          hasPoster: true,
          posters: [{ imageUrl: "/mock/poster-demo-1.png", note: null }],
          delayMs: 3600,
        };
      }
      if (t === "3" || t.includes("检查") || t.includes("违禁") || t.includes("体检")) {
        return { reply: MATERIAL_CHECK_REPLY, delayMs: 2200 };
      }
      return { reply: MATERIAL_COPY_REPLY, delayMs: 2200 };
    }
    default:
      return { reply: "（mock 模式）功能开发中。", delayMs: 300 };
  }
}
